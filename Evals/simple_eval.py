from deepeval import evaluate

from deepeval.test_case import (
    LLMTestCase,
    SingleTurnParams
)

from deepeval.metrics import (
    AnswerRelevancyMetric,        #does the answer address the question
    FaithfulnessMetric,           #is the answer grouned in the context
    ContextualRelevancyMetric,    # are the retrievd are relevent 
    ContextualPrecisionMetric,    #are good chunks ranked first
    ContextualRecallMetric,       #did retrival find the required docs
    GEval             
)


# ============================================================
# 1. HR DATA SOURCE
# ============================================================

hr_document = """
HR Leave Policy

Employees are entitled to 20 days of annual leave per year.

Employees are entitled to 10 days of sick leave per year.

Annual leave must be approved by the reporting manager.

Employees can work from home two days per week.
"""


# ============================================================
# 2. QUESTION
# ============================================================

question = "How many annual leaves are employees entitled to?"


# ============================================================
# 3. EXPECTED / REFERENCE ANSWER  ground truth golden
# ============================================================

expected_answer = (
    "Employees are entitled to 20 days of annual leave per year."
)


# ============================================================
# 4. RETRIEVED CONTEXT
#
# In a REAL RAG application:
#
# Chroma -> Retriever -> These chunks
#
# Here we manually simulate the retriever.
# ============================================================

retrieval_context = [

    "Employees are entitled to 20 days of annual leave per year.",

    "Annual leave must be approved by the reporting manager."

]


# ============================================================
# 5. ACTUAL ANSWER
#
# In a REAL RAG application:
#
# Retriever -> Context -> LLM -> Actual Answer
#
# Here we manually simulate the LLM answer.
# ============================================================

actual_answer = (
    "Employees are entitled to 20 days of annual leave per year."
)


# ============================================================
# 6. DISPLAY INPUT DATA
# ============================================================

print("=" * 80)
print("                    SIMPLE HR RAG EVALUATION")
print("=" * 80)


print("\nDATA SOURCE")
print("-" * 80)
print(hr_document)


print("\nQUESTION")
print("-" * 80)
print(question)


print("\nEXPECTED / REFERENCE ANSWER")
print("-" * 80)
print(expected_answer)


print("\nRETRIEVED CONTEXT")
print("-" * 80)

for i, context in enumerate(
    retrieval_context,
    start=1
):
    print(f"\n--- Retrieved Chunk {i} ---")
    print(context)


print("\nACTUAL ANSWER")
print("-" * 80)
print(actual_answer)


# ============================================================
# 7. CREATE DEEPEVAL TEST CASE
# ============================================================

test_case = LLMTestCase(

    # User question
    input=question,

    # Answer generated by application
    actual_output=actual_answer,

    # Human verified correct answer
    expected_output=expected_answer,

    # What RAG actually retrieved
    retrieval_context=retrieval_context,

    # Original source / golden context
    context=[hr_document]
)


# ============================================================
# 8. CREATE METRICS
# ============================================================

print("\n")
print("=" * 80)
print("                    CREATING METRICS")
print("=" * 80)


# ------------------------------------------------------------
# Answer Relevancy
# ------------------------------------------------------------

answer_relevancy = AnswerRelevancyMetric(

    threshold=0.7,

    model="gpt-4.1",

    include_reason=True,

    # Important for your current issue:
    # run synchronously
    async_mode=False
)


# ------------------------------------------------------------
# Faithfulness
# ------------------------------------------------------------

faithfulness = FaithfulnessMetric(

    threshold=0.7,

    model="gpt-4.1",

    include_reason=True,

    async_mode=False
)


# ------------------------------------------------------------
# Contextual Relevancy
# ------------------------------------------------------------

contextual_relevancy = ContextualRelevancyMetric(

    threshold=0.7,

    model="gpt-4.1",

    include_reason=True,

    async_mode=False
)


# ------------------------------------------------------------
# Contextual Precision
# ------------------------------------------------------------

contextual_precision = ContextualPrecisionMetric(

    threshold=0.7,

    model="gpt-4.1",

    include_reason=True,

    async_mode=False
)


# ------------------------------------------------------------
# Contextual Recall
# ------------------------------------------------------------

contextual_recall = ContextualRecallMetric(

    threshold=0.7,

    model="gpt-4.1",

    include_reason=True,

    async_mode=False
)


# ------------------------------------------------------------
# Correctness
# ------------------------------------------------------------

correctness = GEval(

    name="Correctness",

    criteria="""
    Determine whether the actual answer is factually correct
    compared with the expected answer.

    Give a high score when the actual answer contains the
    same important facts as the expected answer.

    Semantically equivalent answers should receive a high score.

    Give a low score when the actual answer is incorrect,
    incomplete, or contradicts the expected answer.
    """,

    evaluation_params=[

        SingleTurnParams.INPUT,

        SingleTurnParams.ACTUAL_OUTPUT,

        SingleTurnParams.EXPECTED_OUTPUT

    ],

    threshold=0.7,

    model="gpt-4.1"
)


# ============================================================
# 9. RUN DEEPEVAL
# ============================================================

print("\n")
print("=" * 80)
print("                    RUNNING DEEPEVAL")
print("=" * 80)

print("\nPlease wait...")
print("DeepEval is using GPT-4.1 as the evaluation judge.")


evaluate(

    test_cases=[test_case],

    metrics=[

        answer_relevancy,

        faithfulness,

        contextual_relevancy,

        contextual_precision,

        contextual_recall,

        correctness

    ]
)


# ============================================================
# 10. COLLECT METRICS
# ============================================================

metrics = [

    (
        "Answer Relevancy",
        answer_relevancy
    ),

    (
        "Faithfulness",
        faithfulness
    ),

    (
        "Contextual Relevancy",
        contextual_relevancy
    ),

    (
        "Contextual Precision",
        contextual_precision
    ),

    (
        "Contextual Recall",
        contextual_recall
    ),

    (
        "Correctness",
        correctness
    )

]


# ============================================================
# 11. DISPLAY RESULTS
# ============================================================

print("\n")
print("=" * 80)
print("                    EVALUATION RESULTS")
print("=" * 80)


for name, metric in metrics:

    print("\n")
    print(name)
    print("-" * 60)

    # Score
    if metric.score is not None:

        print(
            f"Score : {metric.score:.2f}"
        )

    else:

        print(
            "Score : N/A"
        )


    # Pass / Fail
    try:

        print(
            f"Pass  : {metric.is_successful()}"
        )

    except Exception:

        print(
            "Pass  : N/A"
        )


    # Reason
    if getattr(metric, "reason", None):

        print(
            f"Reason: {metric.reason}"
        )


# ============================================================
# 12. FINAL RESULT
# ============================================================

print("\n")
print("=" * 80)
print("                    FINAL RESULT")
print("=" * 80)


successful_metrics = []

for name, metric in metrics:

    try:

        successful_metrics.append(
            metric.is_successful()
        )

    except Exception:

        successful_metrics.append(False)


if all(successful_metrics):

    print("\nPASS")

    print(
        "All evaluation metrics passed the 0.70 threshold."
    )

else:

    print("\nFAIL")

    print(
        "One or more evaluation metrics failed."
    )


print("\n")
print("=" * 80)
print("                         DONE")
print("=" * 80)